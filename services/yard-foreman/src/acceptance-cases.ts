// Second audit (2026-10-11): checking a test's imports cannot constrain arbitrary JavaScript, so the Foreman no longer
// writes test code at all. It writes acceptance cases, data only, and Yard renders every frozen test file from the one
// template below. Each case runs the builder's program as a separate process (`node src/cli.js ...args`, through
// Stood's harness) with the given input, and expects its exit status and output, exactly or as a substring.
export type AcceptanceCase = Readonly<{
  name: string;
  args: readonly string[];
  input: string;
  status: number;
  output: string;
  match: 'exact' | 'includes';
}>;
export const CASES_FORMAT = 'stood.cases@1';

class Invalid extends Error {}
const bad = (): never => {
  throw new Invalid();
};
const plain = (v: unknown, max: number, empty = true): v is string =>
  typeof v === 'string' && v.length <= max && (empty || v.trim().length > 0) && !v.includes('\0');

// The cases, checked, or null when anything about them is not exactly the format.
export function acceptanceCases(value: unknown): AcceptanceCase[] | null {
  try {
    return checkedCases(value);
  } catch (error) {
    if (error instanceof Invalid) return null;
    throw error;
  }
}
function checkedCases(value: unknown): AcceptanceCase[] {
  if (!Array.isArray(value) || value.length < 1 || value.length > 20) bad();
  const cases = (value as unknown[]).map((raw) => {
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) bad();
    const c = raw as Record<string, unknown>;
    const keys = Object.keys(c).sort().join();
    if (keys !== 'args,input,match,name,output,status') bad();
    if (
      !plain(c.name, 200, false) ||
      !Array.isArray(c.args) ||
      c.args.length > 20 ||
      !c.args.every((a) => plain(a, 500)) ||
      !plain(c.input, 10_000) ||
      !Number.isInteger(c.status) ||
      (c.status as number) < 0 ||
      (c.status as number) > 255 ||
      !plain(c.output, 10_000) ||
      (c.match !== 'exact' && c.match !== 'includes') ||
      (c.match === 'includes' && !(c.output as string).length)
    )
      bad();
    return {
      name: c.name as string,
      args: [...(c.args as string[])],
      input: c.input as string,
      status: c.status as number,
      output: c.output as string,
      match: c.match as 'exact' | 'includes',
    };
  });
  if (new Set(cases.map((c) => c.name)).size !== cases.length) bad();
  return cases;
}

// The only test code that is ever frozen. The cases are embedded as JSON (data, never code).
export function renderAcceptanceTest(cases: readonly AcceptanceCase[]): string {
  return `// Generated by Yard from the plan's acceptance cases (${CASES_FORMAT}). Do not edit: the frozen test bundle hash covers this file.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { runBuilder } from 'stood-harness';

const cases = ${JSON.stringify(cases, null, 2)};

for (const c of cases)
  test(c.name, () => {
    const run = runBuilder(['node', 'src/cli.js', ...c.args], { input: c.input });
    assert.equal(run.status, c.status, 'exit status');
    if (c.match === 'exact') assert.equal(run.stdout, c.output, 'output');
    else assert.ok(run.stdout.includes(c.output), \`output includes \${JSON.stringify(c.output)}\`);
  });
`;
}
